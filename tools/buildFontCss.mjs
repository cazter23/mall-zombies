// Writes src/fonts/fonts.css (one @font-face per bundled face) from config/typefaces.js `families`.
// The .woff2 files in src/fonts/files/ are the Latin subsets from the Fontsource packages (jsDelivr:
// cdn.jsdelivr.net/npm/@fontsource/<slug>/files/<slug>-latin-<weight>-<normal|italic>.woff2). Run: node tools/buildFontCss.mjs
import { writeFileSync, existsSync } from 'node:fs';
import { families } from '../src/config/typefaces.js';

const slug = (name) => name.toLowerCase().replaceAll(' ', '-');
const out = ['/* GENERATED by tools/buildFontCss.mjs from src/config/typefaces.js: do not edit by hand. Latin subsets, bundled so the game (and the single-file build) shows them offline. */'];
for (const [name, def] of Object.entries(families)) {
  const faces = [...def.weights.map((w) => [w, 'normal']), ...(def.italic ?? []).map((w) => [w, 'italic'])];
  for (const [weight, style] of faces) {
    const file = `${slug(name)}-latin-${weight}-${style}.woff2`;
    if (!existsSync(new URL(`../src/fonts/files/${file}`, import.meta.url))) throw new Error(`missing font file ${file}`);
    out.push(`@font-face { font-family: "${name}"; font-style: ${style}; font-weight: ${weight}; font-display: block; src: url("./files/${file}") format("woff2"); }`);
  }
}
writeFileSync(new URL('../src/fonts/fonts.css', import.meta.url), out.join('\n') + '\n');
console.log(`${out.length - 1} font faces`);
